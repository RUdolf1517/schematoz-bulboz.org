def _redis():
    from ..extensions import get_redis
    return get_redis()


def _parse(data) -> tuple[str, str] | None:
    if isinstance(data, list) and data:
        data = data[0]
    if not isinstance(data, dict):
        return None
    text = data.get("quoteText") or data.get("quote") or data.get("text") or data.get("content") or data.get("q")
    author = data.get("quoteAuthor") or data.get("author") or data.get("a") or ""
    if isinstance(text, str) and 3 <= len(text) <= 400 and is_russian(text):
        return text.strip(), str(author).strip()[:80]
    return None


def is_russian(text: str) -> bool:
    """Хотя бы половина букв — кириллица."""
    letters = [c for c in text if c.isalpha()]
    return bool(letters) and sum("а" <= c.lower() <= "я" or c.lower() == "ё" for c in letters) * 2 >= len(letters)


def _remote(kind: str, urls: str, default_author: str) -> dict | None:
    """Цитата из кэша/внешнего API или None."""
    try:
        if not current_app.config.get("QUOTES_REMOTE") or not urls:
            return None
        r = _redis()
        key = f"quotes:{kind}"
        cached = r.lrange(key, 0, -1) or []
        if not r.exists(f"{key}:backoff"):
            import httpx
            url = rng.choice([u.strip() for u in urls.split(",") if u.strip()])
            try:
                resp = httpx.get(url, timeout=TIMEOUT, headers={"Accept": "application/json"})
                got = _parse(resp.json()) if resp.status_code == 200 else None
            except Exception:  # noqa: BLE001 — любой сбой сети = идём в кэш/корпус
                got = None
            if got:
                item = json.dumps({"text": got[0], "author": got[1] or default_author, "source": url}, ensure_ascii=False)
                r.lpush(key, item)
                r.ltrim(key, 0, CACHE_MAX - 1)
                cached.insert(0, item)
            else:
                r.set(f"{key}:backoff", 1, ex=BACKOFF)
        cached = [c for c in cached if is_russian(json.loads(c).get("text", ""))]
        if cached:
            q = json.loads(rng.choice(cached))
            return {"lines": [{"who": q["author"], "text": q["text"]}], "book": "через API", "remote": True}
    except Exception:  # noqa: BLE001
        return None
    return None


# ---------------------------------------------------------------- цитаты из админки
KINDS = {"dubious": "Спорные (облачко и «Погладить»)", "philo": "Философы («Поговорить»)"}
CUSTOM_KEY = "quotes:custom:{}"
CUSTOM_TTL = 3600


def _custom(kind: str) -> list[dict]:
    """Админские цитаты из Redis-кэша (заполняет ensure_custom / refresh_custom)."""
    try:
        raw = _redis().get(CUSTOM_KEY.format(kind))
        return json.loads(raw) if raw else []
    except Exception:  # noqa: BLE001
        return []


async def refresh_custom(s) -> None:
    from sqlalchemy import select
    from ..models import Quote
    rows = (await s.scalars(select(Quote).where(Quote.enabled.is_(True)))).all()
    r = _redis()
    for kind in KINDS:
        items = [{"who": q.author, "text": q.body, "book": q.source} for q in rows if q.kind == kind]
        r.set(CUSTOM_KEY.format(kind), json.dumps(items, ensure_ascii=False), ex=CUSTOM_TTL)


async def ensure_custom() -> None:
    """Подгрузить кэш, если его нет (рестарт Redis / истёк TTL). Дёшево: один EXISTS."""
    if _redis().exists(CUSTOM_KEY.format("dubious")):
        return
    from ..db import session_scope
    async with session_scope() as s:
        await refresh_custom(s)


def _pick(builtin_n: int, kind: str):
    """Встроенные и админские цитаты в одном равновероятном пуле."""
    custom = _custom(kind)
    i = rng.randrange(builtin_n + len(custom))
    return None if i < builtin_n else custom[i - builtin_n]


def dubious(remote: bool = True) -> dict:
    if remote and rng.random() < REMOTE_SHARE:
        q = _remote("dubious", current_app.config.get("QUOTES_DUBIOUS_URLS", ""), "Неизвестный мудрец")
        if q:
            return q
    c = _pick(len(DUBIOUS), "dubious")
    if c:
        return {"lines": [{"who": c["who"], "text": c["text"]}], "book": c["book"], "remote": False, "custom": True}
    who, src, text = rng.choice(DUBIOUS)
    return {"lines": [{"who": who, "text": text}], "book": src, "remote": False}


def philosophy() -> dict:
    if rng.random() < REMOTE_SHARE:
        q = _remote("philo", current_app.config.get("QUOTES_PHILO_URLS", ""), "Неизвестный философ")
        if q:
            return q
    c = _pick(len(PHILO), "philo")
    if c:
        return {"lines": [{"who": c["who"], "text": c["text"]}], "book": c["book"], "remote": False, "custom": True}
    book, lines = rng.choice(PHILO)
    return {"lines": [{"who": w, "text": t} for w, t in lines], "book": book, "remote": False}


def as_speech(q: dict) -> str:
    """Гриб говорит сам, от первого лица: только текст, без «как говорил…» и автора."""
    return " ".join(l["text"] for l in q["lines"])


def as_text(q: dict) -> str:
    return as_speech(q)
