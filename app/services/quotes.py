def _redis():
    from ..extensions import get_redis
    return get_redis()


def _parse(data) -> tuple[str, str] | None:
    if isinstance(data, list) and data:
        data = data[0]
    if not isinstance(data, dict):
        return None
    text = data.get("quote") or data.get("text") or data.get("content") or data.get("q")
    author = data.get("author") or data.get("a") or ""
    if isinstance(text, str) and 3 <= len(text) <= 400:
        return text.strip(), str(author)[:80]
    return None


def _remote(kind: str, urls: str, default_author: str) -> dict | None:
    """Цитата из кэша/внешнего API или None."""
    try:
        if not current_app.config.get("QUOTES_REMOTE") or not urls:
            return None
        r = _redis()
        key = f"quotes:{kind}"
        cached = r.lrange(key, 0, -1) or []
        if not r.exists(f"{key}:backoff"):
            import httpx
            url = rng.choice([u.strip() for u in urls.split(",") if u.strip()])
            try:
                resp = httpx.get(url, timeout=TIMEOUT, headers={"Accept": "application/json"})
                got = _parse(resp.json()) if resp.status_code == 200 else None
            except Exception:  # noqa: BLE001 — любой сбой сети = идём в кэш/корпус
                got = None
            if got:
                item = json.dumps({"text": got[0], "author": got[1] or default_author, "source": url}, ensure_ascii=False)
                r.lpush(key, item)
                r.ltrim(key, 0, CACHE_MAX - 1)
                cached.insert(0, item)
            else:
                r.set(f"{key}:backoff", 1, ex=BACKOFF)
        if cached:
            q = json.loads(rng.choice(cached))
            return {"lines": [{"who": q["author"], "text": q["text"]}], "book": "в оригинале, через API",
                    "remote": True}
    except Exception:  # noqa: BLE001
        return None
    return None


def dubious() -> dict:
    if rng.random() < REMOTE_SHARE:
        q = _remote("dubious", current_app.config.get("QUOTES_DUBIOUS_URLS", ""), "Канье Уэст")
        if q:
            return q
    who, src, text = rng.choice(DUBIOUS)
    return {"lines": [{"who": who, "text": text}], "book": src, "remote": False}


def philosophy() -> dict:
    if rng.random() < REMOTE_SHARE:
        q = _remote("philo", current_app.config.get("QUOTES_PHILO_URLS", ""), "Стоик")
        if q:
            return {**q, "intro": rng.choice(MUSH_INTRO)}
    book, lines = rng.choice(PHILO)
    return {"lines": [{"who": w, "text": t} for w, t in lines], "book": book, "remote": False,
            "intro": rng.choice(MUSH_INTRO)}


def as_text(q: dict) -> str:
    return " ".join(f"{l['who']}: «{l['text']}»" for l in q["lines"]) + (f" ({q['book']})" if q.get("book") else "")
