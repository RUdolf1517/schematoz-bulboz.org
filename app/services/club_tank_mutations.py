"""Боевые мутации Гриб-Танка: 5 на каждую из 6 стадий = 30.

Каждая мутация даёт **бой** (урон рейду/войне, здоровье, защита) и берёт за это **плату уходом**:
повышенная потребность в показателях (шкала коридора сужается), ускоренное падение, выцветание.
Так работает принцип из ТЗ: «все мутации боевые, однако взамен увеличиваются требования к уходу».

Добываются в лаборатории кооператива: участники сдают до 3 своих грибов и соединяют
мутации одной стадии (services/clubs.py::craft_mutation). После крафта мутации у сданных
незамороженных грибов исчезают, а гриб получает дебаф «Раненый» на неделю
(kombucha.wounded_until — ускоряет падение показателей вдвое).
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class TankMutation:
    code: str
    stage: int
    title: str
    emoji: str
    desc: str
    dmg: int = 0                       # добавка урона в рейде/войне
    hp: int = 0                        # добавка к максимальному здоровью Танка
    defense: float = 0.0               # снижение входящего урона (доля)
    mold_resist: float = 0.0           # шанс не заболеть плесенью
    club_xp: float = 0.0              # бонус опыта клуба (%)
    demand: dict[str, float] = field(default_factory=dict)   # требование к показателю: множитель нижней границы
    decay: float = 0.0                 # ускорение падения показателей Танка
    color: str | None = None           # цвет облика (радиоактивно-зелёный и т.п.)
    upkeep: str = ""                   # человекочитаемая плата уходом


def _m(code: str, stage: int, title: str, emoji: str, desc: str, upkeep: str, **kw) -> TankMutation:
    return TankMutation(code=code, stage=stage, title=title, emoji=emoji, desc=desc, upkeep=upkeep, **kw)


