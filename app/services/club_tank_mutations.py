BY_CODE = {m.code: m for m in MUTATIONS}
BY_STAGE: dict[int, list[TankMutation]] = {}
for _mut in MUTATIONS:
    BY_STAGE.setdefault(_mut.stage, []).append(_mut)

assert len(MUTATIONS) == 30 and all(len(v) >= 5 for v in BY_STAGE.values())
assert len(BY_CODE) == len(MUTATIONS)


def for_stage(stage: int) -> list[TankMutation]:
    return BY_STAGE.get(stage, [])


def attack_damage(codes: list[str] | set[str]) -> int:
    """Урон Танка в рейде/войне: база 5 + сумма боевых мутаций (минимум из ТЗ — 5)."""
    total = 5 + sum(BY_CODE[c].dmg for c in codes if c in BY_CODE)
    return max(5, total)


def defense(codes: list[str] | set[str]) -> float:
    return min(0.7, sum(BY_CODE[c].defense for c in codes if c in BY_CODE))


def hp_bonus(codes: list[str] | set[str]) -> int:
    return sum(BY_CODE[c].hp for c in codes if c in BY_CODE)


def club_xp_bonus(codes: list[str] | set[str]) -> float:
    return sum(BY_CODE[c].club_xp for c in codes if c in BY_CODE)


def mold_resist(codes: list[str] | set[str]) -> float:
    return min(0.8, sum(BY_CODE[c].mold_resist for c in codes if c in BY_CODE))


def decay_bonus(codes: list[str] | set[str]) -> float:
    return sum(BY_CODE[c].decay for c in codes if c in BY_CODE)


def demand_scale(codes: list[str] | set[str], stat: str) -> float:
    """Во сколько раз поднялась нижняя граница показателя из-за мутаций."""
    scale = 1.0
    for code in codes:
        m = BY_CODE.get(code)
        if not m:
            continue
        need = m.demand.get(stat)
        if not need:
            continue
        scale = max(scale, need) if need > 2 else scale + (need - 1.0)
    return round(scale, 3)
